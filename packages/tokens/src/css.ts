import { cssVar, type ResolvedTheme } from "./resolve";
import type { Mode } from "./schema";

/** Selector for a theme, optionally pinned to a mode. */
export function themeSelector(id: string, mode?: Mode): string {
  return mode ? `[data-theme="${id}"][data-mode="${mode}"]` : `[data-theme="${id}"]`;
}

function block(selector: string, scheme: Mode, vars: Record<string, string>): string {
  const lines = Object.entries(vars).map(([path, value]) => `  ${cssVar(path)}: ${value};`);
  return `${selector} {\n  color-scheme: ${scheme};\n${lines.join("\n")}\n}`;
}

/**
 * CSS for one theme. The bare `[data-theme]` selector carries the default mode;
 * each other supported mode only overrides what differs.
 *
 * The build uses Style Dictionary for the shipped files; this is the same output
 * for runtime use (theme builder preview and export). A test keeps them in sync.
 */
export function themeCss(theme: ResolvedTheme): string {
  const base = theme.values[theme.modes.default] ?? {};
  const blocks = [block(themeSelector(theme.id), theme.modes.default, base)];
  for (const mode of theme.modes.supported) {
    blocks.push(block(themeSelector(theme.id, mode), mode, diff(base, theme.values[mode] ?? {}, mode === theme.modes.default)));
  }
  blocks.push(...variantBlocks(theme));
  return blocks.join("\n\n") + "\n";
}

/** `[data-theme][data-variant]` blocks. Shared by the Style Dictionary build and runtime CSS. */
export function variantBlocks(theme: ResolvedTheme): string[] {
  const out: string[] = [];
  for (const [name, perMode] of Object.entries(theme.variants ?? {})) {
    const base = perMode[theme.modes.default] ?? {};
    out.push(block(`${themeSelector(theme.id)}[data-variant="${name}"]`, theme.modes.default, base));
    for (const mode of theme.modes.supported) {
      if (mode === theme.modes.default) continue;
      out.push(block(`${themeSelector(theme.id, mode)}[data-variant="${name}"]`, mode, perMode[mode] ?? {}));
    }
  }
  return out;
}

function diff(base: Record<string, string>, next: Record<string, string>, same: boolean): Record<string, string> {
  if (same) return {};
  return Object.fromEntries(Object.entries(next).filter(([k, v]) => base[k] !== v));
}

/** Map a flat token path to the Tailwind v4 theme variable it should become. */
export function tailwindVar(path: string): string | null {
  const [group, ...rest] = path.split(".");
  const name = rest.join("-");
  switch (group) {
    case "color":
      return `--color-${name}`;
    case "radius":
      return `--radius-${name}`;
    case "shadow":
      return `--shadow-${name}`;
    case "font":
      return `--font-${name}`;
    case "size":
      return `--spacing-${name}`; // h-control, w-sidebar, etc.
    case "space":
      return null; // Tailwind's 4px spacing scale already matches; exposed as CSS vars only
    default:
      return null;
  }
}

/**
 * Tailwind v4 entry: wipes Tailwind's default palette (so `bg-red-500` simply doesn't exist)
 * and maps every semantic token to a utility via CSS variables.
 */
export function tailwindThemeCss(paths: string[]): string {
  const mapped = paths
    .map((p) => [tailwindVar(p), cssVar(p)] as const)
    .filter((pair): pair is readonly [string, string] => pair[0] !== null)
    .map(([tw, gw]) => `  ${tw}: var(${gw});`);
  return [
    "/* Generated by @gitwork/tokens. Do not edit. */",
    "@theme {",
    "  --color-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --font-*: initial;",
    "}",
    "",
    "@theme inline {",
    "  --color-transparent: transparent;",
    "  --color-current: currentColor;",
    ...mapped,
    "}",
    "",
  ].join("\n");
}

/** Apply a theme's values as inline CSS variables (for live previews on a sub-tree). */
export function themeStyle(values: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(values).map(([path, value]) => [cssVar(path), value]));
}
